// double equal does types coercion.
// compare the values after converting them to a common type. if the value are equal after type coercion, it returns true.
// if the value are not equal after type coercion , it return false


console.log(2 == 2); // true
console.log(2 == '2'); // true
console.log(1 == true); // true
console.log(0 == false); // true
console.log(null == undefined); // true
console.log(NaN == NaN); // false

